#!/usr/bin/env python3
"""
Generate ntp/config.js and the extension icon set from branding/brand.json.

The New Tab Page is a Manifest V3 extension: it cannot read files from the repo
at runtime, so brand data is baked in at build time. This script is the only
bridge between brand.json and the shipped NTP - if you need a new value in the
UI, add it to brand.json and to the CONFIG template below, never hardcode it in
app.js.

Run:  python scripts/gen-ntp-config.py
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BRAND = ROOT / "branding" / "brand.json"
NTP = ROOT / "ntp"
VERSION_FILE = ROOT / "VERSION"


def read_version(brand: dict) -> str:
    if VERSION_FILE.exists():
        value = VERSION_FILE.read_text(encoding="utf-8").strip()
        if value:
            return value
    return brand["versions"]["initial"]


def build_config(brand: dict, version: str) -> dict:
    return {
        "name": brand["product"]["name"],
        "shortName": brand["product"]["shortName"],
        "version": version,
        "tagline": brand["product"]["tagline"],
        "homepage": brand["product"]["homepage"],
        "colors": brand["colors"],
        "search": {
            "url": "https://duckduckgo.com/?q={query}",
            "engine": brand["urls"]["defaultSearchEngine"],
        },
        "speedDial": brand["speedDial"],
    }


def main() -> int:
    if not BRAND.exists():
        print(f"error: {BRAND} missing", file=sys.stderr)
        return 1

    brand = json.loads(BRAND.read_text(encoding="utf-8"))
    version = read_version(brand)
    config = build_config(brand, version)

    banner = (
        "/* AUTO-GENERATED by scripts/gen-ntp-config.py from branding/brand.json.\n"
        "   Do not edit by hand - changes are overwritten on every build. */\n"
    )
    body = "window.STGR_CONFIG = " + json.dumps(config, indent=2, ensure_ascii=False) + ";\n"
    (NTP / "config.js").write_text(banner + body, encoding="utf-8")

    # Extension icons must be real PNG files next to the manifest.
    assets = NTP / "assets"
    assets.mkdir(parents=True, exist_ok=True)
    src_dir = ROOT / "branding" / "icons" / "png"
    for size in (16, 32, 48, 128):
        src = src_dir / f"{size}.png"
        if src.exists():
            shutil.copyfile(src, assets / f"icon-{size}.png")
        else:
            print(f"warning: {src} missing - run branding/generate-icons.py first", file=sys.stderr)

    # Manifest version must track the product version or the store/updater breaks.
    manifest_path = NTP / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    manifest["version"] = version
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    print(f"ntp config generated (version {version})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
